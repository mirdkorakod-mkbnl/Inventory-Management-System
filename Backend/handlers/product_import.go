// PreviewImportProducts godoc
// @Summary      Preview import products
// @Description  Preview product data from CSV / Excel file before importing (no database insert)
// @Description
// @Description  Supported file types:
// @Description  - CSV (.csv)
// @Description  - Excel (.xlsx, .xls)
// @Description
// @Description  Expected columns:
// @Description  name, price, stock (code is optional and auto-generated)
// @Tags         Products Import/Export
// @Accept       multipart/form-data
// @Produce      json
// @Param        file  formData  file  true  "CSV / Excel file to preview"
// @Success      200   {object}  map[string]interface{} "Preview result with total and preview rows"
// @Failure      400   {object}  map[string]string
// @Security     BearerAuth
// @Router       /api/products/import/preview [post]
func PreviewImportProducts(c *fiber.Ctx) error {
    rows, err := readImportFile(c)
    if err != nil {
        return c.Status(400).JSON(fiber.Map{"error": err.Error()})
    }

    preview := []fiber.Map{}

    for i, row := range rows {
        if i == 0 {
            continue // skip header
        }
        
        if len(row) < 3 {
            continue // skip ถ้าไม่มีเพียงพอ
        }

        preview = append(preview, fiber.Map{
            "name":  row[0],
            "price": row[1],
            "stock": row[2],
        })
    }

    return c.JSON(fiber.Map{
        "total":   len(preview),
        "preview": preview,
    })
}

// DownloadProductTemplate godoc
// @Summary      Download product import template
// @Description  Download Excel template for importing products
// @Description
// @Description  Columns:
// @Description  name | price | stock
// @Description
// @Description  Notes:
// @Description  - code can be empty (auto-generated by system)
// @Description  - ID is auto-generated by database
// @Tags         Products Import/Export
// @Produce      application/vnd.openxmlformats-officedocument.spreadsheetml.sheet
// @Success      200  {file}  file "Excel template file"
// @Security     BearerAuth
// @Router       /api/products/import/template [get]
func DownloadProductTemplate(c *fiber.Ctx) error {
    f := excelize.NewFile()
    sheet := "Template"
    f.SetSheetName("Sheet1", sheet)

    headers := []string{"name","price", "stock"}
    for i, h := range headers {
        cell, _ := excelize.CoordinatesToCellName(i+1, 1)
        f.SetCellValue(sheet, cell, h)
    }

    f.SetCellValue(sheet, "A2", "Keyboard")
    f.SetCellValue(sheet, "B2", 20000)
    f.SetCellValue(sheet, "C2", 10)

    c.Set("Content-Type", "application/vnd.openxmlformats-officedocument.spreadsheetml.sheet")
    c.Set("Content-Disposition", "attachment; filename=products_template.xlsx")

    return f.Write(c.Response().BodyWriter())
}

