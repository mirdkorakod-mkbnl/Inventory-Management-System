// ImportProducts godoc
// @Summary      Import products (admin)
// @Description  Import products using CSV file (Admin only)
//
// @Description  CSV format example:
// @Description
// @Description  name,price,stock
// @Description  Keyboard,20000,10
// @Description  Mouse,10000,5
// @Description  Monitor,150000,3
//
// @Tags         Products Import/Export
// @Accept       multipart/form-data
// @Produce      json
// @Param        file  formData  file  true  "CSV file to import"
// @Success      200   {object}  map[string]interface{}
// @Failure      400   {object}  map[string]string
// @Security     BearerAuth
// @Router       /api/admin/products/import [post]
func ImportProducts(c *fiber.Ctx) error {
	userID := getUserID(c)

	rows, err := readImportFile(c)
	if err != nil {
		return err
	}

	success := 0
	failed := 0

	for i, row := range rows {
		if i == 0 {
			continue // skip header
		}

		if len(row) < 3 {
			failed++
			continue
		}

		price, err1 := strconv.ParseFloat(row[1], 64)
		stock, err2 := strconv.Atoi(row[2])
		if err1 != nil || err2 != nil {
			failed++
			continue
		}

		product := models.Product{
			Name:   row[0],
			Price:  price,
			Stock:  stock,
			Code:   utils.GenerateProductCode(),
			UserID: userID,
		}

		if err := database.DB.Create(&product).Error; err != nil {
			failed++
		} else {
			success++
		}
	}

	return c.JSON(fiber.Map{
		"message": "Import completed",
		"success": success,
		"failed":  failed,
	})
}

